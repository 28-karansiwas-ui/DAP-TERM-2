number_cols = ["Items_Count", "Order_Value", "Discount_Pct", "Delivery_Fee", "Distance_Km", "Delivery_Time_Min", "Rating", "Final_Amount"]

# 2. Clean the string columns to numeric values so .describe() works on them
for col in ["Order_Value", "Final_Amount"]:
    if col in df.columns and df[col].dtype == 'object':
        df[col] = pd.to_numeric(df[col].astype(str).str.replace(",", "").str.strip(), errors='coerce')

if "Discount_Pct" in df.columns and df["Discount_Pct"].dtype == 'object':
    df["Discount_Pct"] = pd.to_numeric(df["Discount_Pct"].astype(str).str.replace("%", "").str.strip(), errors='coerce')

